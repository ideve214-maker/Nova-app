#!/usr/bin/env bash
# Generate launcher icons + splash for a Capacitor project from resources/.
# Usage: generate-icons.sh <project-dir> <android|ios>
#
# @capacitor/assets 3.0.5 prefers a sibling assets/ directory and exits 0 even
# when it generated nothing, which is how earlier packages shipped the default
# Capacitor icon. So: always --assetPath resources, and fail unless the
# launcher icon files were (re)written by this run.
set -euo pipefail
PROJ="${1:?project dir}"
PLATFORM="${2:?android or ios}"
cd "$PROJ"

[ -s resources/icon.png ] || [ -s resources/icon-only.png ] || {
  echo "ERROR: no resources/icon.png or resources/icon-only.png in $PROJ" >&2
  exit 1
}
MARK="$(mktemp)"
sleep 1

if [ -x scripts/generate-capacitor-assets.sh ] || [ -f scripts/generate-capacitor-assets.sh ]; then
  # The admin app ships its own generator (resources/ only, fails hard,
  # brand colours). Use it so packaging matches the app repo.
  echo "==> using app's scripts/generate-capacitor-assets.sh"
  bash scripts/generate-capacitor-assets.sh
else
  BG="${ICON_BG:-#05070E}"
  mkdir -p www
  [ -f www/manifest.json ] || echo '{}' > www/manifest.json
  npx capacitor-assets generate "--${PLATFORM}" --assetPath resources \
    --iconBackgroundColor "$BG" --iconBackgroundColorDark "$BG" \
    --splashBackgroundColor "$BG" --splashBackgroundColorDark "$BG"
fi

if [ "$PLATFORM" = android ]; then
  WANT=(android/app/src/main/res/mipmap-xxxhdpi/ic_launcher.png
        android/app/src/main/res/mipmap-xxxhdpi/ic_launcher_foreground.png)
else
  WANT=(ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png)
fi
for f in "${WANT[@]}"; do
  [ -s "$f" ] || { echo "ERROR: icon generator did not write $f" >&2; exit 1; }
  [ "$f" -nt "$MARK" ] || { echo "ERROR: $f was not regenerated by this run (default icon?)" >&2; exit 1; }
done
rm -f "$MARK"
echo "ICONS_OK $PLATFORM"
